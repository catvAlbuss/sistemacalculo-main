import {readFileSync, existsSync} from 'node:fs';
import {join} from 'node:path';
import * as dm from '@mlightcad/data-model';
const R = new URL('../../', import.meta.url).href;
const {createDrawingContext} = await import(R + 'resources/js/ingenieria/cad/drawingContext.js');
const {SKILLS} = await import(R + 'resources/js/ingenieria/agente/skills/index.js');
const {instalarRecorteXclip} = await import(R + 'resources/js/etabs/visor/recorteXclip.js');
const {PLANOS} = await import(R + 'scripts/agente/planos.mjs');
const {paresDelManifiesto} = await import(R + 'scripts/agente/pares-entrenamiento.mjs');
const {cargarPlantillaAdaptativa, cargarDetallesEstandar} = await import(R + 'scripts/agente/plantilla.mjs');
const filtro = process.argv[2] ?? 'vinchos/modulo-08';
const BASE = join(PLANOS, 'estructuras');
const par = paresDelManifiesto(BASE, JSON.parse(readFileSync(join(BASE, 'pares.json'), 'utf8')), existsSync).find((p) => `${p.grupo}/${p.id}` === filtro);
const {AcDbLibreDwgMainThreadConverter} = await import('@mlightcad/libredwg-converter/node');
dm.AcDbDatabaseConverterManager.instance.register(dm.AcDbFileType.DWG, new AcDbLibreDwgMainThreadConverter());
instalarRecorteXclip({AcDbLibreDwgConverter: (await import('@mlightcad/libredwg-converter')).AcDbLibreDwgConverter, AcDbBlockReference: dm.AcDbBlockReference});
const db = new dm.AcDbDatabase(); const b = readFileSync(par.rutaArquitectura);
await db.read(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength), {readOnly: true}, dm.AcDbFileType.DWG);
const datos = {hz: '0.60', df: '2.00', zona: '3', suelo: 'S2', categoria: 'A2', normaE030: '2018'};
const ctx = createDrawingContext({getDatabase: () => db, dm, loadTemplate: cargarPlantillaAdaptativa, getProjectData: () => ({...datos}), setProjectData: () => {}, afterDraw: () => {}});
ctx.memoria ??= {}; ctx.detallesEstandar = cargarDetallesEstandar();
const r = await SKILLS.find((s) => s.name === 'plano_estructuras').run({}, ctx);
console.log('=== MENSAJE ===\n' + r.mensaje); console.log('=== RESUMEN ===\n' + (r.resumen ?? '')); console.log('=== PARA EL INGENIERO ===\n' + (r.paraElIngeniero ?? '')); console.log('=== AVISOS ===\n' + (r.avisos ?? []).join('\n'));
console.log('=== OTROS CAMPOS ===', Object.keys(r).join(', '));
console.log('=== COHERENCIA ===', JSON.stringify(r.coherencia));
const textos = ctx.entidadesDelAgente().filter((e) => /TEXT/i.test(e.dxfTypeName)).map((e) => String(e.contents ?? e.textString ?? ''));
const { writeFileSync } = await import('node:fs'); writeFileSync((process.env.TEMP ?? '.') + '/textos-plano.txt', textos.join('\n'));
console.log('textos dibujados:', textos.length);
